-- Our ministry: the nations where the ministry is present, in the order it
-- reached them (the list "Les 154 nations"). The app shows them on a globe.

-- [country_code]: ISO code (flag, name translated in the app), '' for a
-- region that is not a country (Écosse, Andaman et Nicobar…). [latitude] and
-- [longitude]: its place on the globe (Natural Earth label points, or by hand
-- for the small places). [arrival_year]: filled in over time.
CREATE TABLE ministry_nations (
    id BIGSERIAL PRIMARY KEY,
    position INT NOT NULL CHECK (position > 0),
    name TEXT NOT NULL,
    country_code TEXT NOT NULL DEFAULT '',
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    arrival_year INT CHECK (arrival_year BETWEEN 1900 AND 2200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- checked at the end of a transaction: a nation moves, the others follow
    CONSTRAINT ministry_nations_position_key UNIQUE (position) DEFERRABLE INITIALLY DEFERRED
);

